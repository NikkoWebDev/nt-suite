#!/usr/bin/env bash
# Builds the Instan't palette seeder module APK (com.instant.themeseeder).
#
# The seeder is a minimal legacy Xposed module (assets/xposed_init + classes.dex) that
# LSPatch embeds alongside InstaEclipse-Legacy. Its embedded SeedData is generated here
# from config/{profile,palette} so a rebuilt config yields a new seed version and the
# module only runs on first use of that configuration.
#
# Usage: build_seed_module.sh <s21|universal|all>
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SEED_DIR="$DIR/scripts/seed-module"
CONFIG_DIR="$DIR/config"
DIST_DIR="$DIR/dist"

SDK="${ANDROID_SDK_ROOT:-$HOME/Android/Sdk}"
PLATFORM_JAR="$(ls "$SDK/platforms/android-3"*/android.jar 2>/dev/null | sort -V | tail -n 1)"
BUILD_TOOLS="$(ls -d "$SDK/build-tools/"* 2>/dev/null | sort -V | tail -n 1)"

if [ ! -f "$PLATFORM_JAR" ]; then
    echo "[ERROR] android.jar no encontrado en $SDK/platforms" >&2
    exit 1
fi
if [ ! -d "$BUILD_TOOLS" ]; then
    echo "[ERROR] build-tools no encontradas en $SDK/build-tools" >&2
    exit 1
fi

profiles_arg="${1:-s21}"
if [ "$profiles_arg" = "all" ]; then profiles_arg="s21 universal"; fi

mkdir -p "$SEED_DIR/gen/com/instant/themeseeder" "$SEED_DIR/classes" "$SEED_DIR/stub-classes" "$SEED_DIR/build" "$DIST_DIR"

for profile in $profiles_arg; do
    echo "[seed] perfil: $profile"

    # 1) Flag JSON (all names must be InstaEclipse pref keys — the module ignores unknown ones) + seed version
    python3 - "$CONFIG_DIR/palette-dark.json" "$CONFIG_DIR/profile-$profile.json" "$SEED_DIR/gen/com/instant/themeseeder/SeedData.java" "$profile" <<'PYEOF'
import json, sys, zlib

palette_path, profile_path, dst, profile = sys.argv[1:5]
palette = json.load(open(palette_path, encoding="utf-8"))["palette"]
pflags = json.load(open(profile_path, encoding="utf-8"))["flags"]
light_id = json.load(open(palette_path.replace("palette-dark", "palette-light"), encoding="utf-8"))["lightPresetId"]

features = dict(pflags)
features.update({"customThemeEnabled": True})
# Seed blob order is canonical: sorted keys, so identical inputs produce identical VERSION.
blob = json.dumps({"features": features, "palette": palette, "light": light_id},
                  sort_keys=True, separators=(",", ":"))
version = zlib.crc32(blob.encode()) & 0x7FFFFFFF

def java_str(s):
    out = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
    return '"' + out + '"'

body = f'''package com.instant.themeseeder;

/* Generated by scripts/build_seed_module.sh from config/palette-dark.json + config/profile-{profile}.json. */
public final class SeedData {{
    public static final int VERSION = {version};
    public static final int LIGHT_PRESET_ID = {light_id};
    public static final String FEATURES_JSON = {java_str(json.dumps(features, separators=(',', ':')))};
    public static final String PALETTE_JSON = {java_str(json.dumps(palette, separators=(',', ':')))};
}}
'''
with open(dst, "w", encoding="utf-8") as fh:
    fh.write(body)
print(f"[seed]   SeedData v{version} lightPresetId={light_id} flags={len(features)}")
PYEOF

    # 2) Compile stubs into a private classpath (never emitted into the module dex)
    find "$SEED_DIR/stub-classes" -name '*.class' -delete 2>/dev/null || true
    find "$SEED_DIR/classes" -name '*.class' -delete 2>/dev/null || true
    javac --release 11 -nowarn -cp "$PLATFORM_JAR" -d "$SEED_DIR/stub-classes" $(find "$SEED_DIR/stubs-src" -name '*.java')

    # 3) Compile the seeder against the stubs; output contains solely our classes
    javac --release 11 -nowarn \
        -cp "$SEED_DIR/stub-classes:$PLATFORM_JAR" \
        -d "$SEED_DIR/classes" \
        "$SEED_DIR/src/com/instant/themeseeder/Seeder.java" \
        "$SEED_DIR/gen/com/instant/themeseeder/SeedData.java" 2>&1

    class_files=$(find "$SEED_DIR/classes" -name '*.class')
    if echo "$class_files" | grep -q de.robv; then
        echo "[ERROR] stub classes leaked into the module dex" >&2; exit 1
    fi

    # 4) dex
    "$BUILD_TOOLS/d8" --release --min-api 26 --output "$SEED_DIR/build" $class_files
    rm -f "$SEED_DIR/build/classes.jar"

    # 5) package: manifest + assets, then the dex at the root
    mkdir -p "$SEED_DIR/build/assets"
    cp "$SEED_DIR/xposed_init.txt" "$SEED_DIR/build/assets/xposed_init"
    rm -f "$SEED_DIR/build/out.apk"
    "$BUILD_TOOLS/aapt2" link --manifest "$SEED_DIR/AndroidManifest.xml" -I "$PLATFORM_JAR" \
        -A "$SEED_DIR/build/assets" -o "$SEED_DIR/build/out.apk"
    (cd "$SEED_DIR/build" && zip -q out.apk classes.dex)
    "$BUILD_TOOLS/zipalign" -f 4 "$SEED_DIR/build/out.apk" "$SEED_DIR/build/out-aligned.apk"

    # 6) verify the module skeleton the LSPatch loader expects (no grep|pipe: SIGPIPE + pipefail)
    entries=$(zipinfo -1 "$SEED_DIR/build/out-aligned.apk")
    echo "$entries" | grep -q '^assets/xposed_init$' || { echo "[ERROR] xposed_init missing from seeder apk" >&2; exit 1; }
    echo "$entries" | grep -q '^classes.dex$' || { echo "[ERROR] classes.dex missing from seeder apk" >&2; exit 1; }
    if echo "$entries" | grep -q 'de/robv'; then
        echo "[ERROR] stub classes leaked into the dex path list" >&2; exit 1
    fi

    mv -f "$SEED_DIR/build/out-aligned.apk" "$DIST_DIR/seed-$profile.apk"
    echo "[seed]   -> dist/seed-$profile.apk ($(du -h "$DIST_DIR/seed-$profile.apk" | cut -f1))"
done
